def _consultant_url(article: str) -> str:
    """Поиск КонсультантПлюс. Это поисковый URL, он не зависит от внутреннего id документа."""

    return "https://www.consultant.ru/search/?q=" + quote_plus(_consultant_query(article))


def _consultant_query(article: str) -> str:
    text = article.replace("«", " ").replace("»", " ").replace('"', " ")
    text = re.sub(r"О несостоятельности\s*\(банкротстве\)", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"\s+", " ", text).strip(" .;")
    plenum = re.search(
        r"Пленум\w*\s+(ВАС|ВС)\s+РФ\s+от\s+(\d{2}\.\d{2}\.\d{4})\s+№\s*(\d+)",
        text,
        re.IGNORECASE,
    )
    if plenum:
        court = plenum.group(1).upper()
        return f"Пленум {court} РФ от {plenum.group(2)} № {plenum.group(3)}"
    law = re.search(r"ФЗ\s*[-–]?\s*(\d+)", text, re.IGNORECASE)
    if law and re.search(r"ст\.", text, re.IGNORECASE):
        head = re.split(r"ФЗ", text, maxsplit=1, flags=re.IGNORECASE)[0].strip(" .")
        return f"{head} {law.group(1)}-ФЗ"
    return text[:160]


def _ref(article: str, summary: str, url: Optional[str] = None) -> StatutoryReference:
    return StatutoryReference(article=article, summary=summary, url=url or _consultant_url(article))


