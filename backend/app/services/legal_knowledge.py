class LegalKnowledgeService:
    """Возвращает одну и ту же справку для одного и того же stage_code."""

    def build(self, stage_code: str, legal_basis: list[str]) -> LegalKnowledgeBlock:
        requested = "bankruptcy_individual_realization" if stage_code == "bankruptcy_individual_intro" else stage_code
        code: StageCode = requested if requested in _STAGE_CODES else "general_arbitration_dispute"  # type: ignore[assignment]
        base = _CARDS[code]
        articles = list(base.statutory_articles)
        known = {item.article for item in articles}
        for note in self._notes_for_basis(legal_basis):
            if note.article not in known:
                articles.append(note)
                known.add(note.article)
        return base.model_copy(update={"statutory_articles": articles})

    def _notes_for_basis(self, legal_basis: list[str]) -> list[StatutoryReference]:
        found: list[StatutoryReference] = []
        seen: set[tuple[str, str]] = set()
        for clause in legal_basis:
            for key in _keys_in_clause(clause):
                note = _ARTICLE_NOTES.get(key)
                if note is None or key in seen:
                    continue
                seen.add(key)
                found.append(note)
        return found


def _keys_in_clause(clause: str) -> list[tuple[str, str]]:
    lowered = clause.lower()
    if re.search(r"апк", lowered):
        family = "apk"
    elif re.search(r"гк\s*рф", lowered):
        family = "gk"
    elif re.search(r"127|банкрот|несостоятельн", lowered):
        family = "127"
    else:
        family = ""
    numbers = re.findall(
        r"(?:ст(?:ать(?:я|и|ями|ей|е|ю)|\.)\s*)(\d+(?:\.\d+)?)",
        clause,
        flags=re.IGNORECASE,
    )
    if not numbers:
        numbers = re.findall(r"\b(\d{2,3}(?:\.\d{1,2})?)\b", clause)
    keys: list[tuple[str, str]] = []
    for number in numbers:
        if family:
            keys.append((family, number))
        else:
            keys.append(("127", number))
            keys.append(("apk", number))
    return keys
